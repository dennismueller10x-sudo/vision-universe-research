#!/usr/bin/env node
/* V13b LARGECAP-STRICT: writes quant/engines/research-largecap-price-anchors-1.1.0.cjs from docs/quant-recovery/v13b/largecap-strict/cases-1.1.0.json
 * (protocol 1.0.0 + amendment 1.0.1 + amendment 1.1.0). Only UNLOCKED cases become records. --out <path> writes elsewhere (tests).
 * The 1.0.1 registry quant/engines/research-largecap-price-anchors.cjs is not touched. */
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const ROOT = path.resolve(__dirname, '../../../..');
const sha = b => crypto.createHash('sha256').update(b).digest('hex');
const arg = k => { const i = process.argv.indexOf('--' + k); return i > 0 ? process.argv[i + 1] : null; };
const CASES = path.join(ROOT, 'docs/quant-recovery/v13b/largecap-strict/cases-1.1.0.json');

function build() {
  const bytes = fs.readFileSync(CASES), doc = JSON.parse(bytes);
  if (doc.protocolVersion !== '1.1.0' || !doc.amendment110Sha256 || !doc.amendmentSha256) throw Error('CASES_VERSION');
  const src = (p, role) => ({ role, accession: p.accession, url: p.url, sha256: p.sha256,
    claim: (p.type === 'A' ? `fiscal ${p.fy} Q${p.q} high ${p.high} low ${p.low}` : `${p.start}..${p.end} average price paid ${p.avgPrice}`) + (p.pass ? '' : ` (failed, deviation ${p.deviation})`), quote: p.quote });
  const id = q => ({ role: 'IDENTITY_SYMBOL_EXCHANGE', accession: q.accession, url: q.url, sha256: q.sha256, claim: `${q.form} ${q.filingDate} names symbol ${q.symbol} and the exchange`, quote: q.quote });
  const records = doc.cases.filter(c => c.status === 'UNLOCKED').map(c => ({
    securityId: c.securityId, ticker: c.ticker, cik: c.cik, masterRowAction: c.master.masterRowAction, selectedCanonicalId: c.master.selectedCanonicalId, masterRowSet: c.master.masterRowSet,
    validFrom: c.interval.validFrom, validTo: c.interval.validTo, evidenceLevel: 'SEC_PRICE_BAND_AND_SYMBOL', protocolVersion: doc.protocolVersion,
    historyGuard: c.historyGuard, bandConfirmedMoves: c.bandConfirmedMoves, providerFactorsInside: c.factorsInside, anchorsInside: c.anchorsInside,
    identity: { validSymbols: c.identity.validSymbols, firstIdentityFiling: c.identity.firstIdentityFiling, lastIdentityFiling: c.identity.lastIdentityFiling },
    strictBoundary: { v101ValidFrom: c.v101.validFrom, v101ValidTo: c.v101.validTo, start: c.strict.start, end: c.strict.end,
      excludedBandConfirmedMoves: c.bandConfirmedMovesExcluded, clipStart: c.strict.clipStart.length, clipEnd: c.strict.clipEnd.length },
    sources: [src(c.firstPassInside, 'PRICE_ANCHOR_FIRST'), src(c.lastPassInside, 'PRICE_ANCHOR_LAST'), id(c.identity.firstIdentityQuote), id(c.identity.lastIdentityQuote),
      src(c.strict.startEvidence, 'STRICT_START_EVIDENCE'), src(c.strict.endEvidence, 'STRICT_END_EVIDENCE'),
      ...c.strict.clipStart.map(p => src(p, 'STRICT_START_FAILING_PERIOD')), ...c.strict.clipEnd.map(p => src(p, 'STRICT_END_FAILING_PERIOD'))]
  }));
  return { schemaVersion: 'research-largecap-price-anchors-1.1.0', methodId: 'SOURCE_PRICE_BAND_IDENTITY_INTERVAL', ruleId: doc.ruleId, protocolSha256: doc.protocolSha256,
    amendmentSha256: doc.amendmentSha256, amendment110Sha256: doc.amendment110Sha256, casesSha256: sha(bytes), certificationStatus: 'NOT_CERTIFIED', productionApproved: false, records };
}

function render(reg) {
  return '/* GENERATED by scripts/quant/v13b/largecap-strict/build-registry.cjs from docs/quant-recovery/v13b/largecap-strict/cases-1.1.0.json - do not edit.\n'
    + ' * V13b LARGECAP-STRICT research registry (protocol 1.0.0 + amendment 1.0.1 + amendment 1.1.0 STRICT_INTERVAL_BOUNDARY): closed intervals\n'
    + ' * [validFrom, validTo], each a sub-interval of the 1.0.1 interval that contains no day of a failing anchor period outside the run.\n'
    + ' * Read only by the research loader under identityEvidenceProtocolV13LargecapStrict (replaces the 1.0.1 records of the same ids). */\n'
    + "'use strict';\nmodule.exports = " + JSON.stringify(reg, null, 1) + ';\n';
}

if (require.main === module) {
  const out = arg('out') || path.join(ROOT, 'quant/engines/research-largecap-price-anchors-1.1.0.cjs');
  fs.writeFileSync(out, render(build()));
  console.log('wrote', out);
}
module.exports = { build, render };
