#!/usr/bin/env node
/* V13 LARGECAP: writes quant/engines/research-largecap-price-anchors.cjs from docs/quant-recovery/v13/largecap/cases-1.0.0.json
 * (results under protocol 1.0.0 + amendment 1.0.1). Only UNLOCKED cases become records. --out <path> writes elsewhere (tests). */
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const ROOT = path.resolve(__dirname, '../../../..');
const sha = b => crypto.createHash('sha256').update(b).digest('hex');
const arg = k => { const i = process.argv.indexOf('--' + k); return i > 0 ? process.argv[i + 1] : null; };
const CASES = path.join(ROOT, 'docs/quant-recovery/v13/largecap/cases-1.0.0.json');

function build() {
  const bytes = fs.readFileSync(CASES), doc = JSON.parse(bytes);
  if (doc.protocolVersion !== '1.0.1' || !doc.amendmentSha256) throw Error('CASES_VERSION');
  const records = doc.cases.filter(c => c.status === 'UNLOCKED').map(c => {
    const pass = c.periods.filter(p => p.pass && p.start <= c.interval.validTo && p.end >= c.interval.validFrom);
    const first = pass[0], last = pass.at(-1), docSha = new Map(c.documents.map(d => [d.url, d.sha256]));
    const src = (p, role) => ({ role, accession: p.accession, url: p.url, sha256: docSha.get(p.url), claim: p.type === 'A' ? `fiscal ${p.fy} Q${p.q} high ${p.high} low ${p.low}` : `${p.start}..${p.end} average price paid ${p.avgPrice}`, quote: p.quote });
    const id = q => ({ role: 'IDENTITY_SYMBOL_EXCHANGE', accession: q.accession, url: q.url, sha256: q.sha256, claim: `${q.form} ${q.filingDate} names symbol ${q.symbol} and the exchange`, quote: q.quote });
    return {
      securityId: c.securityId, ticker: c.ticker, cik: c.cik, masterRowAction: c.master.masterRowAction, selectedCanonicalId: c.master.selectedCanonicalId, masterRowSet: c.master.masterRowSet,
      validFrom: c.interval.validFrom, validTo: c.interval.validTo, evidenceLevel: 'SEC_PRICE_BAND_AND_SYMBOL', protocolVersion: doc.protocolVersion,
      historyGuard: c.historyGuard, bandConfirmedMoves: c.bandConfirmedMoves, providerFactorsInside: c.factorsInside,
      anchorsInside: c.anchorsInside, identity: { validSymbols: c.identity.validSymbols, firstIdentityFiling: c.identity.firstIdentityFiling, lastIdentityFiling: c.identity.lastIdentityFiling },
      sources: [src(first, 'PRICE_ANCHOR_FIRST'), src(last, 'PRICE_ANCHOR_LAST'), id(c.identity.firstIdentityQuote), id(c.identity.lastIdentityQuote)]
    };
  });
  return { schemaVersion: 'research-largecap-price-anchors-1.0.0', methodId: 'SOURCE_PRICE_BAND_IDENTITY_INTERVAL', protocolSha256: doc.protocolSha256, amendmentSha256: doc.amendmentSha256,
    casesSha256: sha(bytes), certificationStatus: 'NOT_CERTIFIED', productionApproved: false, records };
}

function render(reg) {
  return '/* GENERATED by scripts/quant/v13/largecap/build-registry.cjs from docs/quant-recovery/v13/largecap/cases-1.0.0.json - do not edit.\n'
    + ' * V13 LARGECAP research registry (protocol docs/quant-recovery/v13/largecap/protocol-1.0.0.json + amendment 1.0.1): closed intervals\n'
    + ' * [validFrom, validTo] in which SEC price bands (quarterly high/low tables, repurchase average prices) and symbol/exchange statements\n'
    + ' * of the registrant confirm the provider series. Read only by research-weekly-loader.cjs with identityEvidenceProtocolV13Largecap. */\n'
    + "'use strict';\nmodule.exports = " + JSON.stringify(reg, null, 1) + ';\n';
}

if (require.main === module) {
  const out = arg('out') || path.join(ROOT, 'quant/engines/research-largecap-price-anchors.cjs');
  fs.writeFileSync(out, render(build()));
  console.log('wrote', out);
}
module.exports = { build, render };
